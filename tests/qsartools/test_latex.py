import pytest

from qsartools.latex import RAGGED_X, format_macros, newcommand, tabular_close, tabular_open


def test_newcommand_format():
    assert newcommand("MorganRTwoMean", "0.7592") == "\\newcommand{\\MorganRTwoMean}{0.7592}\n"
    assert newcommand("NCompounds", 859) == "\\newcommand{\\NCompounds}{859}\n"


@pytest.mark.parametrize("name", ["R2Mean", "r2_mean", "Morgan FP", "", "Δmean"])
def test_invalid_names_are_rejected(name):
    with pytest.raises(ValueError, match="only letters"):
        newcommand(name, 1)


def test_format_macros_keeps_order_and_header():
    text = format_macros({"B": 2, "A": "x"}, header="Auto-generated by step 99")
    assert text == "% Auto-generated by step 99\n\\newcommand{\\B}{2}\n\\newcommand{\\A}{x}\n"
    assert format_macros({}) == ""


class TestFullWidthTables:
    """Every generated table has to fill the text width of whichever class renders it, without a box: sn-jnl wraps a
    table in threeparttable and fails on any \\resizebox around the tabular."""

    def test_a_spec_without_x_uses_a_stretchable_intercolumn_skip(self):
        assert tabular_open("llrcc") == r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrcc}"
        assert tabular_close("llrcc") == r"\end{tabular*}"

    def test_a_spec_with_x_uses_tabularx(self):
        spec = "l" + RAGGED_X + "rcc"
        assert tabular_open(spec) == r"\begin{tabularx}{\textwidth}{l>{\raggedright\arraybackslash}Xrcc}"
        assert tabular_close(spec) == r"\end{tabularx}"

    @pytest.mark.parametrize("spec", ["llrcc", "l" + RAGGED_X + "rcc", RAGGED_X + "cc" + RAGGED_X + "c", "lrrrrrr"])
    def test_the_two_halves_always_agree(self, spec):
        # A mismatched pair is the one way this helper can produce a document that does not compile.
        env = tabular_open(spec).split("{", 1)[1].split("}", 1)[0]
        assert tabular_close(spec) == "\\end{" + env + "}"

    @pytest.mark.parametrize("spec", ["llrcc", "l" + RAGGED_X + "rcc"])
    def test_the_target_width_is_always_the_text_width(self, spec):
        assert r"{\textwidth}" in tabular_open(spec)
